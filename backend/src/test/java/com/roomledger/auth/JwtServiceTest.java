package com.roomledger.auth;

import com.roomledger.user.User;
import org.junit.jupiter.api.Test;
import org.springframework.test.util.ReflectionTestUtils;

import java.time.Duration;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;

// Plain unit test: no Spring context, runs in milliseconds.
class JwtServiceTest {

    private static final String SECRET = "unit-test-secret-that-is-long-enough-for-hs256";

    private final JwtService jwtService = new JwtService(new JwtProperties(SECRET, Duration.ofHours(1)));

    private static User userWithId(UUID id) {
        User user = new User("ana@test.ro", "hash", "Ana");
        // The id is normally generated by Hibernate on persist.
        ReflectionTestUtils.setField(user, "id", id);
        return user;
    }

    @Test
    void parsesTheTokenItGenerated() {
        UUID id = UUID.randomUUID();

        String token = jwtService.generateToken(userWithId(id));

        assertThat(jwtService.parse(token))
                .contains(new AuthenticatedUser(id, "ana@test.ro"));
    }

    @Test
    void rejectsTamperedToken() {
        String token = jwtService.generateToken(userWithId(UUID.randomUUID()));
        String tampered = token.substring(0, token.length() - 2) + (token.endsWith("A") ? "BB" : "AA");

        assertThat(jwtService.parse(tampered)).isEmpty();
    }

    @Test
    void rejectsTokenSignedWithAnotherSecret() {
        var otherService = new JwtService(
                new JwtProperties("another-secret-that-is-also-long-enough-xx", Duration.ofHours(1)));
        String foreignToken = otherService.generateToken(userWithId(UUID.randomUUID()));

        assertThat(jwtService.parse(foreignToken)).isEmpty();
    }

    @Test
    void rejectsExpiredToken() {
        var expiringService = new JwtService(new JwtProperties(SECRET, Duration.ofSeconds(-1)));
        String expired = expiringService.generateToken(userWithId(UUID.randomUUID()));

        assertThat(jwtService.parse(expired)).isEmpty();
    }

    @Test
    void rejectsGarbage() {
        assertThat(jwtService.parse("not-a-jwt")).isEmpty();
    }
}
